def render(B):
    h2s = [t for k_, t in B if k_ == "h2"]; hh, tt = [], []
    for k_, t in B:
        if k_ == "toc":
            hh.append("<h2>目次</h2><ul>" + "".join(f"<li>{html.escape(x)}</li>" for x in h2s) + "</ul>")
            tt.append("■ 目次\n" + "\n".join(f"・{x}" for x in h2s))
        elif k_ in ("h2", "h3"):
            hh.append(f"<{k_}>{html.escape(t)}</{k_}>"); tt.append(("■ " if k_ == "h2" else "▼ ") + t)
        elif k_ == "p":
            hh.append("<p>" + re.sub(r"\*\*(.+?)\*\*", lambda m: "<strong>" + html.escape(m.group(1)) + "</strong>", html.escape(t).replace("&amp;", "&")) + "</p>"); tt.append(t.replace("**", ""))
        elif k_ == "ul":
            hh.append("<ul>" + "".join("<li>" + re.sub(r"\*\*(.+?)\*\*", lambda m: "<strong>" + html.escape(m.group(1)) + "</strong>", html.escape(x)) + "</li>" for x in t) + "</ul>"); tt.append("\n".join("・" + x.replace("**", "") for x in t))
        elif k_ == "url":
            hh.append(f"<p>{html.escape(t)}</p>"); tt.append(t)
    return "".join(hh), "\n\n".join(tt)


KJ = ["", "一", "二", "三", "四", "五", "六", "七", "八", "九", "十", "十一", "十二", "十三", "十四", "十五", "十六", "十七", "十八"]
KANA10 = ["", "じゅう", "にじゅう", "さんじゅう", "よんじゅう", "ごじゅう", "ろくじゅう", "ななじゅう", "はちじゅう", "きゅうじゅう"]
def pt_say(x):
    a, b = f"{x:.1f}".split(".")
    n = int(a); t = (("" if n // 10 == 1 else KN[n // 10]) + "十") + (KN[n % 10] if n % 10 else "")
    if n % 10 == 1: t = KANA10[n // 10] + "いち"     # 「三十一」の「一」が読み落とされる（1週前の文字起こし）→ かな
    return t + "点" + ("ちょうど" if b == "0" else KN[int(b)])

def build(k, S_fn, race, date):
    r = MP.R[k]; SC = r["sc"]; RC = r["rc"]
    sc = lambda n: f"{SC[n]['score']:.1f}"
    RN = [x["name"] for x in sorted(SC.values(), key=lambda x: x["rank"])]
    rk_say = lambda n, lead="続いて": f"{lead}、{KJ[SC[n]['rank']]}位は、{n}。指数は、{pt_say(SC[n]['score'])}"
    rank_sub = lambda n: f"{SC[n]['rank']}位 {n} {sc(n)}"
    S = S_fn(SC, RN, sc, rk_say, rank_sub, RC)
    for img, z, fo, nar, subs in S:
        assert "印" not in nar, nar
        for s in subs:
            for n, x in SC.items():
                m = re.search(re.escape(n) + r" (\d{2}\.\d)$", s)
                if m: assert m.group(1) == f"{x['score']:.1f}", (s, x["score"])
    scenes = [dict(id=i, image=f"{img}.png", sec=8.0, zoom=z, narration=nar, subtitle=subs, **({"focus": dict(x=fo[0], y=fo[1], z=fo[2])} if fo else {}))
              for i, (img, z, fo, nar, subs) in enumerate(S, 1)]
    out = ROOT / r["dir"] / "long" / f"script_{k}_draw.json"
    out.write_text(json.dumps(dict(race=race, date=date, image_dir=f"images_{k}", out_suffix="long",
        canvas=dict(w=1920, h=1080, fg_w=1620, fg_h=1080, y_off=0, zmax=1.04, font=46, hilite=50, margin_v=40, wrap=28), scenes=scenes),
        ensure_ascii=False, indent=1), encoding="utf-8")
    print(out.name, len(scenes), "場面", sum(len(s[3]) for s in S), "字")


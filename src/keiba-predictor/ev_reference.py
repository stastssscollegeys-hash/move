def ticket_band(ticket: str, pops) -> dict | None:
    """券種と人気の組み合わせから実測値を引く。未測定は None"""
    tbl = TICKET_BANDS.get(ticket)
    if not tbl:
        return None
    key = tuple(pops) if ticket == "馬単" else tuple(sorted(pops))
    return tbl.get(key)


# 🔴 2026-09-09 hold-out検証の結果、加点方向の補正は廃止した。
#
# 発見に使っていない288レースで検定したところ:
#   ・候補2帯は**棄却**（馬連4-6人気は 120% → hold-out 20%、P(>100%)=0.0%）
#   ・帯の順位相関も 0.10〜0.27 と弱く、**「中位人気が割安」は再現しなかった**
#       ワイド4-6人気  in-sample 97% → hold-out **51%**
#       ワイド2-4人気  in-sample 89% → hold-out 68%
#   ・再現したのは**下位人気帯が確実に悪いこと**だけ
#       ワイド8-10人気 in-sample 13% → hold-out **0%**
#       ワイド1-2/1-3人気は 80%→73%/81% と安定（凡庸なまま安定）
#
# つまり血統で得た結論と同じ: **「買う理由」には使えず、「消す理由」にしか使えない。**
# よって係数は 1.0 を上限とし、悪い帯を減点する方向にだけ効かせる。
BAND_PENALTY_CUT = 0.60      # 除外後ROIがこれ未満の帯は減点対象


def band_quality(ticket: str, pops) -> float:
    """
    人気の組み合わせによる補正係数。**1.0以下しか返さない（減点専用）**。

    hold-outで再現しなかった「割安な帯を加点する」用途には使えない。
    再現したのは「下位人気同士は確実に悪い」という負の情報だけなので、
    そこだけを反映する。
    """
    b = ticket_band(ticket, pops)
    if not b:
        return 0.95                       # 未測定はごく軽い減点にとどめる
    roi = b.get("roi_ex_top", 0.0)
    if roi >= BAND_PENALTY_CUT:
        return 1.0                        # 平凡以上は素通し（加点しない）
    # 悪い帯だけ、悪さに比例して落とす
    return max(0.10, roi / BAND_PENALTY_CUT)


def wide_band(pop_a: int, pop_b: int):
    """人気の組み合わせから実測値を引く。未測定の組み合わせは None"""
    return WIDE_BANDS.get(tuple(sorted((int(pop_a), int(pop_b)))))


def wide_quality(pop_a: int, pop_b: int) -> float:
    """
    そのワイドの「割安さ」係数。実測の除外後ROIを全組み合わせ平均で割ったもの。
    1.0より大きいほど市場が過小評価している組み合わせ。
    未測定（人気10位以下など）は保守的に 0.85 を返す。
    """
    b = wide_band(pop_a, pop_b)
    if not b:
        return 0.85
    mean = sum(v[3] for v in WIDE_BANDS.values()) / len(WIDE_BANDS)
    return b[3] / mean



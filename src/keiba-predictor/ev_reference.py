    import json
    base = Path.home() / "Desktop" / "競馬予想レポート" / "daily_pdca" / "db"
    p = base / "ticket_bands.json"
    if not p.exists():
        return
    try:
        d = json.load(open(p, encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return

    for t, rows in (d.get("tickets") or {}).items():
        tbl = {}
        for k, v in rows.items():
            try:
                pops = tuple(int(x) for x in k.split("-"))
            except ValueError:
                continue
            tbl[pops] = v
            if (v.get("hits", 0) >= 15 and v.get("roi_ex_top", 0) >= 1.0
                    and sum(1 for x in v.get("thirds", []) if x >= 1.0) == 3):
                ROBUST_BANDS.append((t, pops))
            if t == "ワイド" and len(pops) == 2:
                WIDE_BANDS[pops] = (v["n"], v["hit_rate"], v["roi"],
                                    v["roi_ex_top"], v["median"])
        TICKET_BANDS[t] = tbl
    globals()["WIDE_BANDS_RACES"] = d.get("races", 0)



def _font(size, bold=True):
    fname = 'BIZ-UDGothicB.ttc' if bold else 'BIZ-UDGothicR.ttc'
    try:
        return ImageFont.truetype(os.path.join(_FONT_DIR, fname), size, index=0)
    except Exception:
        return ImageFont.load_default()

def _hex(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))

def _gradient(draw, y1, y2, c1, c2, w):
    for y in range(y1, y2):
        t = (y - y1) / max(1, y2 - y1)
        r = int(c1[0] + (c2[0] - c1[0]) * t)
        g = int(c1[1] + (c2[1] - c1[1]) * t)
        b = int(c1[2] + (c2[2] - c1[2]) * t)
        draw.line([(0, y), (w, y)], fill=(r, g, b))

def _stroke(draw, x, y, text, font, fill=(255,255,255), stroke=(0,0,0), sw=4):
    """アウトライン付きテキスト描画"""
    for dx in range(-sw, sw+1):
        for dy in range(-sw, sw+1):
            if abs(dx) + abs(dy) <= sw:
                draw.text((x+dx, y+dy), text, font=font, fill=stroke)
    draw.text((x, y), text, font=font, fill=fill)

def _cx_stroke(draw, text, font, y, W, fill=(255,255,255), stroke=(0,0,0), sw=4):
    """中央揃えアウトライン付きテキスト"""
    bb = draw.textbbox((0, 0), text, font=font)
    x = (W - (bb[2] - bb[0])) // 2
    _stroke(draw, x, y, text, font, fill, stroke, sw)

def _load_chara(path=_CHARA_PATH, target_h=340):
    """キャラクターシートから前向き（左1/3）を切り出し、白背景をflood-fillで除去"""
    img = Image.open(path).convert('RGBA')
    W, H = img.size
    zone = img.crop((0, 0, W // 3, H))
    data = np.array(zone)
    r, g, b = data[:,:,0], data[:,:,1], data[:,:,2]

    # 近白ピクセルを検出
    near_white = (r > 228) & (g > 228) & (b > 228)

    # 連結成分のうち画像端に接するもの（=背景）のみ透過
    labeled, _ = scipy_label(near_white)
    border_labels = set()
    border_labels.update(labeled[0, :].tolist())
    border_labels.update(labeled[-1, :].tolist())
    border_labels.update(labeled[:, 0].tolist())
    border_labels.update(labeled[:, -1].tolist())
    border_labels.discard(0)
    bg_mask = np.isin(labeled, list(border_labels))
    data[:,:,3] = np.where(bg_mask, 0, data[:,:,3])

    char = Image.fromarray(data)
    bbox = char.getbbox()
    if bbox:
        char = char.crop(bbox)

    aspect = char.width / char.height
    new_w = int(target_h * aspect)
    return char.resize((new_w, target_h), Image.LANCZOS)


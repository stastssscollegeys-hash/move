def set_font(run, size=10, bold=False, color=None):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)


def para(doc, t, size=10, bold=False, color=None):
    p = doc.add_paragraph(); set_font(p.add_run(t), size, bold, color); p.paragraph_format.space_after = Pt(2)


def table(doc, rows):
    tb = doc.add_table(rows=0, cols=len(rows[0])); tb.style = 'Table Grid'
    for i, row in enumerate(rows):
        cells = tb.add_row().cells
        for j, v in enumerate(row):
            cells[j].text = ''
            set_font(cells[j].paragraphs[0].add_run(str(v)), 9, i == 0)
    doc.add_paragraph()


def post(doc, title, lines, limit=None):
    n = len('\n'.join(lines))
    para(doc, f"{title}（{n}字{'/' + str(limit) + '字 ' + ('OK' if n <= limit else '⚠超過') if limit else ''}）", 11, True, (70, 70, 70))
    tb = doc.add_table(rows=1, cols=1); tb.style = 'Table Grid'
    cell = tb.cell(0, 0); cell.text = ''
    for i, ln in enumerate(lines):
        p = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        set_font(p.add_run(ln), 9.5)
    doc.add_paragraph()
    if limit and n > limit:
        print(f'[WARN] {title} {n}字 > {limit}')



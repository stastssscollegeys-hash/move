def set_font(run, pt=10.5, bold=False, color=None):
    run.font.name = FONT; run.font.size = Pt(pt); run.font.bold = bold
    if color: run.font.color.rgb = color
    rpr = run._r.get_or_add_rPr()
    f = OxmlElement('w:rFonts')
    f.set(qn('w:hint'), 'eastAsia'); f.set(qn('w:eastAsia'), FONT)
    rpr.insert(0, f)

def box(doc, content, bg="F5F5F5"):
    tbl = doc.add_table(rows=1, cols=1); tbl.style = 'Table Grid'
    cell = tbl.rows[0].cells[0]; tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'),'clear'); shd.set(qn('w:color'),'auto'); shd.set(qn('w:fill'),bg)
    tcPr.append(shd)
    for line in content.strip().split('\n'):
        p = cell.add_paragraph(); run = p.add_run(line); set_font(run)
    doc.add_paragraph()


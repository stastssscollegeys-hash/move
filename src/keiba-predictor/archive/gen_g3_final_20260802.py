def set_font(run, size=10, bold=False, color=None):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)

def h1(text, color=(15,71,97)):
    p = doc.add_heading(text, level=1)
    for r in p.runs:
        set_font(r, 14); r.font.color.rgb = RGBColor(*color)

def h2(text, color=(40,40,40)):
    p = doc.add_heading(text, level=2)
    for r in p.runs:
        set_font(r, 12); r.font.color.rgb = RGBColor(*color)

def body(text, size=10, bold=False):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_font(r, size, bold=bold)
    return p

def box(lines, size=10):
    p = doc.add_paragraph()

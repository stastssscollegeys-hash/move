def c(n):
    return CIRC[int(n)]


def sf(run, size=10, bold=False, color=None):
    run.font.name = FONT; run.font.size = Pt(size); run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)


def h1(doc, t, col=(20, 60, 140)):
    p = doc.add_paragraph(); sf(p.add_run(t), 13, True, col)


def h2(doc, t, col=(70, 70, 70)):
    p = doc.add_paragraph(); sf(p.add_run(t), 11, True, col)


def box(doc, lines):
    tb = doc.add_table(rows=1, cols=1); tb.style = 'Table Grid'
    cell = tb.cell(0, 0); cell.text = ''
    for i, ln in enumerate(lines):
        p = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        sf(p.add_run(ln), 9.5)
    doc.add_paragraph()


def note(doc, t, col=(0, 90, 160)):
    p = doc.add_paragraph(); sf(p.add_run(t), 9, False, col)


def post(doc, title, lines, limit=None):
    n = len("\n".join(lines))
    tag = f"（{n}字/{limit}字 {'OK' if n <= limit else '⚠超過'}）" if limit else f"（{n}字）"
    h2(doc, f"{title} {tag}")
    box(doc, lines)
    if limit and n > limit:
        print(f"[WARN] 超過 {title} {n}字")



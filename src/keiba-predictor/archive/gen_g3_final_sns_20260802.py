def set_font(run, size=10, bold=False):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)

def h1(text, color=(15,71,97)):
    p = doc.add_heading(text, level=1)
    for r in p.runs:
        set_font(r, 14); r.font.color.rgb = RGBColor(*color)

def h3(text):
    p = doc.add_heading(text, level=3)
    for r in p.runs:
        set_font(r, 11)

def box(lines, size=10):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.5)
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(8)
    r = p.add_run("\n".join(lines))
    set_font(r, size)

def threads_post(title, lines):
    """Threads投稿: 500字制限を自動チェックして見出しに文字数を表示"""
    text = "\n".join(lines)
    n = len(text)
    status = "OK" if n <= 500 else "⚠超過!要短縮"
    h3(f"{title}（{n}字/500字 {status}）")
    if n > 500:
        print(f"[WARN] Threads文字数超過: {title} = {n}字")
    box(["【コピー用】"] + lines)


def table(rows):
    tbl = doc.add_table(rows=0, cols=len(rows[0])); tbl.style = "Light Grid Accent 1"
    for row in rows:
        cells = tbl.add_row().cells
        for i, v in enumerate(row): cells[i].text = str(v)
    doc.add_paragraph()

def threads_post(title, text, ask=None):
    """ask=会話誘発文（Threadsアルゴリズムは会話の往復を評価・2026-08-19戦略）。
    ハッシュタグ行の直前に挿入する。"""
    if ask:
        lines = text.rstrip().split("\n")
        tag_i = next((i for i in range(len(lines)-1, -1, -1) if lines[i].startswith("#")), None)
        if tag_i is not None:
            lines.insert(tag_i, ask + "\n")
            text = "\n".join(lines)
        else:
            text = text.rstrip() + "\n\n" + ask
    n = len(text.replace("\n", ""))
    flag = "OK" if n <= 500 else "⚠超過"
    h3(f"{title}（{n}字/500字 {flag}）")
    box(text)
    print(("[OK] " if n <= 500 else "[WARN] ") + f"{title}: {n}字")



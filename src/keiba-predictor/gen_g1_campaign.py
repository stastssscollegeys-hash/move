def thread(doc, title, parent, children):
    """1投稿で出す。冒頭(parent)だけで言いたいことが完結し、その先に根拠(children)を続ける。
    冒頭は140字/8行以内＝「さらに表示」を開かなくても全部見える範囲。"""

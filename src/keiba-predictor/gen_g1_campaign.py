    ok = "OK" if (pn <= 140 and pl <= 8) else ("⚠字数超過" if pn > 140 else "⚠行数超過")
    lines = list(parent)
    for lab, ls in children:
        lines += ["", SEP, f"■ {lab}", SEP] + [x for x in ls if x != TAGS]
    while lines and lines[-1] == "":
        lines.pop()
    lines += ["", TAGS]
    total = len("\n".join(lines))
    h2(doc, f"{title}　［冒頭 {pn}字/{pl}行 … {ok}／全体 {total}字］")
    body(doc, "　太字＝「さらに表示」を開かずに見える部分。ここだけで投稿の言いたいことが完結している。", 9)
    tb = doc.add_table(rows=1, cols=1); tb.style = "Table Grid"
    cell = tb.cell(0, 0); cell.text = ""
    for i, ln in enumerate(lines):
        p = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        set_font(p.add_run(ln), 9.5, i < pl)
    doc.add_paragraph()
    if pn > 140 or pl > 8:
        print(f"[NOTE] 冒頭が基準超え {title} {pn}字/{pl}行")
    if total > 2000:
        print(f"[WARN] 全体が2000字超 {title} {total}字")

